/* A tiny check macro shared by the tests. */
#ifndef LGP_TEST_CHECK_H
#define LGP_TEST_CHECK_H

#include <stdio.h>

static int checks, failures;

#define CHECK(cond, ...)                                 \
    do {                                                 \
        checks++;                                        \
        if (!(cond)) {                                   \
            failures++;                                  \
            fprintf(stderr, "FAIL line %d: ", __LINE__); \
            fprintf(stderr, __VA_ARGS__);                \
            fputc('\n', stderr);                         \
        }                                                \
    } while (0)

#endif
