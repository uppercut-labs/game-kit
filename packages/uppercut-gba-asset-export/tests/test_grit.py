import pytest
from uppercut_gba_asset_export import DEFAULT_HEADER, DEFAULT_SOURCE, c_name, grit_files

WORDS = [0x11111111, 0, 0, 0, 0, 0, 0, 0x0000000F, 0xAABBCCDD, 1, 2, 3, 4, 5, 6, 7]
PALETTE = list(range(16))


def test_c_name_replaces_everything_but_word_characters() -> None:
    assert c_name("city-tiles.v2") == "city_tiles_v2"
    assert c_name("font_8x8") == "font_8x8"


def test_default_files_are_grit_shaped() -> None:
    files = grit_files("city-tiles", WORDS, PALETTE, width=16, height=8)
    assert files.header == (
        "//{{BLOCK(city_tiles)\n\n"
        "//======================================================================\n"
        "//\n"
        "//\tcity_tiles, 16x8@4,\n"
        "//\t+ palette 16 entries, not compressed\n"
        "//\t+ 2 tiles not compressed\n"
        "//\tGenerated by uppercut-gba-asset-export\n"
        "//\n"
        "//======================================================================\n\n"
        "#ifndef GRIT_CITY_TILES_H\n#define GRIT_CITY_TILES_H\n\n"
        "#define city_tilesTilesLen 64\nextern const unsigned int city_tilesTiles[16];\n\n"
        "#define city_tilesPalLen 32\nextern const unsigned short city_tilesPal[16];\n\n"
        "#endif // GRIT_CITY_TILES_H\n\n//}}BLOCK(city_tiles)\n"
    )
    assert files.source == (
        "//{{BLOCK(city_tiles)\n\n"
        '#include "city-tiles.h"\n\n'
        "const unsigned int city_tilesTiles[16] __attribute__((aligned(4))) =\n{\n"
        "\t0x11111111,0x00000000,0x00000000,0x00000000,0x00000000,0x00000000,0x00000000,0x0000000F,\n"
        "\t0xAABBCCDD,0x00000001,0x00000002,0x00000003,0x00000004,0x00000005,0x00000006,0x00000007,\n"
        "};\n\n"
        "const unsigned short city_tilesPal[16] __attribute__((aligned(4))) =\n{\n"
        "\t0x0000,0x0001,0x0002,0x0003,0x0004,0x0005,0x0006,0x0007,\n"
        "\t0x0008,0x0009,0x000A,0x000B,0x000C,0x000D,0x000E,0x000F,\n"
        "};\n\n//}}BLOCK(city_tiles)\n"
    )


def test_layout_options() -> None:
    files = grit_files("a", WORDS[:8], PALETTE, width=8, height=8, indent="    ", separator=", ", palette_per_line=16, trailing_comma=False)
    assert "    0x11111111, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x0000000F\n" in files.source
    assert "    0x0000, 0x0001, 0x0002, 0x0003, 0x0004, 0x0005, 0x0006, 0x0007, 0x0008, 0x0009, 0x000A, 0x000B, 0x000C, 0x000D, 0x000E, 0x000F\n};" in files.source


def test_palette_indent_can_differ_from_tile_indent() -> None:
    files = grit_files("a", WORDS[:8], PALETTE, width=8, height=8, indent="    ", palette_indent="", palette_per_line=16, palette_trailing_comma=False)
    assert "    0x11111111," in files.source
    assert "0x0000000F,\n" in files.source  # the tile rows keep their trailing comma
    assert "\n0x0000,0x0001," in files.source and "0x000E,0x000F\n" in files.source  # the palette: no indent, no trailing comma


def test_custom_templates_get_the_fields() -> None:
    header = "// {name}: {width}x{height}, {tile_count} tiles, {tiles_len} bytes, {word_count} words, {C_NAME}\n"
    source = "{tile_rows}\n--\n{palette_rows}\n"
    files = grit_files("x-y", WORDS, PALETTE, width=16, height=8, header_template=header, source_template=source)
    assert files.header == "// x-y: 16x8, 2 tiles, 64 bytes, 16 words, X_Y\n"
    assert files.source.startswith("\t0x11111111,")
    assert DEFAULT_HEADER.count("{{") >= 2 and "{{BLOCK" in DEFAULT_SOURCE


def test_bad_input() -> None:
    with pytest.raises(ValueError):
        grit_files("a", WORDS, PALETTE[:15], width=16, height=8)
    with pytest.raises(ValueError):
        grit_files("a", WORDS[:7], PALETTE, width=8, height=8)
