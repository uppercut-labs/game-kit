#!/usr/bin/env python3
"""Tests for tools/gen_bitmap_font.py: the source parser, the three outputs and the freshness check."""
import importlib.util
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("gen_bitmap_font", HERE.parent / "tools" / "gen_bitmap_font.py")
gen = importlib.util.module_from_spec(spec)
sys.modules["gen_bitmap_font"] = gen  # dataclasses look the module up by name
spec.loader.exec_module(gen)

failures = 0


def check(condition, message):
    global failures
    if not condition:
        failures += 1
        print("FAIL", message, file=sys.stderr)


def raises(text, fragment):
    try:
        gen.parse(text)
    except gen.SourceError as error:
        return fragment in str(error)
    return False


TINY = """
; a comment
font 3x2 advance 4
glyph 0x41 ; A
.#.
###

glyph 66
#.#
##.
font 2x1 advance 3
glyph 0x30
##
"""

# --- the parser
fonts = gen.parse(TINY)
check(list(fonts) == ["3x2", "2x1"], "fonts keep file order")
a = fonts["3x2"]
check((a.width, a.height, a.advance) == (3, 2, 4), "font metrics")
check(a.glyphs[0x41] == (".#.", "###") and a.glyphs[66] == ("#.#", "##."), "glyph rows, hex and decimal codes")
check(a.row_value(0x41, 0) == 0b010 and a.row_value(0x41, 1) == 0b111, "row values put the leftmost pixel in the high bit")
check((a.first, a.last) == (0x41, 0x42), "range")

check(raises("glyph 0x41\n#\n", "before any font"), "glyph before font")
check(raises("font 3x2 advance 4\nglyph 0x41\n.#.\n", "has 1 rows"), "short glyph")
check(raises("font 3x2 advance 4\nglyph 0x41\n.#\n###\n", "2 wide"), "narrow row")
check(raises("font 3x2 advance 4\nglyph 0x41\n.#.\n###\nglyph 0x41\n.#.\n###\n", "appears twice"), "duplicate glyph")
check(raises("font 3x2 advance 4\nfont 3x2 advance 4\n", "appears twice"), "duplicate font")
check(raises("font 3x2\n", "expected 'font"), "malformed font line")
check(raises("font 9x2 advance 4\n", "1 to 8"), "too wide")
check(raises("font 3x2 advance 4\nglyph 300\n", "0..255"), "code out of range")
check(raises("font 3x2 advance 4\nglyph x\n", "0..255"), "code not a number")
check(raises("font 3x2 advance 4\n", "no glyphs"), "font without glyphs")
check(raises("", "no fonts"), "empty source")
check(raises("font 3x2 advance 4\n.#.\n", "outside a glyph"), "row outside a glyph")
check(raises("font 3x2 advance 4\nglyph 0x41\nabc\n", "unexpected text"), "junk")

# --- the shipped source
real = gen.load()
check(list(real) == ["5x7", "8x8", "3x5"], "the shipped fonts")
check(len(real["5x7"].glyphs) == 67 and len(real["8x8"].glyphs) == 64 and len(real["3x5"].glyphs) == 67, "glyph counts")
check(real["8x8"].first == 0x20 and real["8x8"].last == 0x5F, "8x8 covers 0x20 to 0x5F with no gaps")
check(sorted(real["8x8"].glyphs) == list(range(0x20, 0x60)), "8x8 has every code in its range")
check(all(c not in real["5x7"].glyphs for c in range(ord("a"), ord("z") + 1)), "5x7 has no lowercase")

# --- the C tables
header = gen.tables_header(real)
check(header.startswith("/* Generated by tools/gen_bitmap_font.py"), "header banner")
check("#define BFONT_5X7_COUNT 95" in header and "#define BFONT_8X8_COUNT 64" in header, "counts")
check("0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11, /* 0x41 'A' */" in header, "the row for A")
check(header == gen.tables_header(real), "deterministic")

# --- standalone arrays
a5 = gen.array_header(real["5x7"], name="g_font", type_name="u8", first=32, count=96, guard="G_FONT_H", include="types.h")
check(a5.count("\n [") == 67, "one designated entry per glyph")
check(" [33] = {14,17,17,31,17,17,17},  /* 0x41 'A' */" in a5, "A in decimal at index 33")
check("static const u8 g_font[96][7] = {" in a5 and "#ifndef G_FONT_H" in a5 and '#include "types.h"' in a5, "frame")
check(a5.endswith("#endif\n"), "guard closed")
d8 = gen.array_header(real["8x8"], name="FONT_GLYPHS", type_name="u8", layout="dense", number_format="hex")
check("static const u8 FONT_GLYPHS[64][8] = {" in d8, "dense 8x8 declaration")
check("    { 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00 },  /* 0x41 'A' */" in d8, "dense hex row for A")
check(d8.count("\n    {") == 64, "every index listed")
try:
    gen.array_header(real["5x7"], name="x", first=40, count=10)
    check(False, "a range that leaves glyphs out is refused")
except gen.SourceError:
    pass

# --- the Python module
py = gen.python_module(real["5x7"], name="FONT_5X7")
scope = {}
exec(compile(py, "_font5x7.py", "exec"), scope)
table = scope["FONT_5X7"]
check(len(table) == 67 and table["A"] == ("01110", "10001", "10001", "11111", "10001", "10001", "10001"), "python table")
check(all(table[chr(c)] == tuple(r.replace(".", "0").replace("#", "1") for r in g) for c, g in real["5x7"].glyphs.items()), "python table equals the source")

# --- command line
with tempfile.TemporaryDirectory() as td:
    out = Path(td) / "t.h"
    check(gen.main(["tables", "--out", str(out)]) == 0 and out.read_text() == header, "tables command writes the header")
    out = Path(td) / "a.h"
    check(gen.main(["array", "--font", "5x7", "--name", "f", "--out", str(out)]) == 0 and "f[67]" not in out.read_text() and "static const unsigned char f[" in out.read_text(), "array command")
    check(gen.main(["array", "--font", "9x9", "--name", "f"]) == 1, "unknown font is an error")
    check(gen.main(["--source", str(Path(td) / "missing.txt"), "tables"]) == 1, "missing source is an error")
check(gen.main(["check"]) == 0, "the generated files in this repository are current")

print("check_generator:", "FAILED" if failures else "all passed")
sys.exit(1 if failures else 0)
