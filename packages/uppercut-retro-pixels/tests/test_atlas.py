def test_metrics_header_without_include_and_wrong_count():
    text = metrics_header([("A", [GlyphRect(0, 0, 0, 0, 0, 1)])], atlas_width=8, atlas_height=8, first_char=65, last_char=65)
    assert "#include" not in text
    assert text.endswith("#endif\n")
    with pytest.raises(ValueError):
        metrics_header([("A", [])], atlas_width=8, atlas_height=8, first_char=65, last_char=65)


GLYPHS = {
    ord("I"): ("01110", "00100", "00100", "00100", "00100", "00100", "01110"),
    ord("."): ("00000", "00000", "00000", "00000", "00000", "01100", "01100"),
}


def test_outlined_cell_atlas_places_ink_and_outline():
    INK, EDGE = 0xFFFF, 0x1234
    blank = ("00000",) * 7
    atlas = outlined_cell_atlas(
        lambda code: GLYPHS.get(code, blank), first=ord("."), last=ord("I"), columns=16, ink=INK, outline=EDGE
    )
    assert len(atlas) == 128 * 128
    cell = lambda idx: [[atlas[((idx // 16) * 12 + y) * 128 + (idx % 16) * 8 + x] for x in range(8)] for y in range(12)]
    dot = cell(0)
    # the dot's two ink rows are rows 5 and 6 of the glyph, placed 2 down: rows 7 and 8; its columns 1 and 2, placed 1 across: 2 and 3
    assert dot[7][2] == INK and dot[7][3] == INK and dot[8][2] == INK and dot[8][3] == INK
    assert dot[6][2] == EDGE and dot[9][3] == EDGE and dot[8][1] == EDGE and dot[8][4] == EDGE
    assert dot[0][0] == 0 and dot[11][7] == 0
    assert sum(1 for row in dot for v in row if v == INK) == 4


def test_outlined_cell_atlas_cells_stay_in_their_cells():
    INK = 7
    atlas = outlined_cell_atlas(
        lambda code: ("11111",) * 7, first=0, last=1, columns=2, cell_width=8, cell_height=12,
        atlas_width=16, atlas_height=12, ink=INK, outline=3,
    )
    # ink columns 1..5 of each cell, outline columns 0 and 6, column 7 clear
    for cell in (0, 1):
        for y in range(12):
            assert atlas[y * 16 + cell * 8 + 7] == 0


def test_outlined_cell_atlas_rejects_a_too_small_atlas():
    with pytest.raises(ValueError):
        outlined_cell_atlas(lambda code: ("1",), first=0, last=300, atlas_width=128, atlas_height=128)
