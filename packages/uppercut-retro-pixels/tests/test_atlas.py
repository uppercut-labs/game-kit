import pytest

from uppercut_retro_pixels import Glyph, GlyphRect, metrics_header, outlined_cell_atlas, pack_glyphs


def solid(char, w, h, value, y_offset=0, advance=None):
    return Glyph(char, w, h, y_offset, advance if advance is not None else w + 1, bytes((value, 0, 0, 255)) * (w * h))


def pixel(atlas, width, x, y):
    i = (y * width + x) * 4
    return tuple(atlas[i : i + 4])


def test_glyphs_pack_left_to_right_with_a_margin_and_wrap_to_a_new_shelf():
    glyphs = [solid(65, 4, 3, 10), solid(66, 4, 5, 20), solid(67, 4, 2, 30)]
    atlas, (rects,) = pack_glyphs([glyphs], 12, 16)
    assert rects[0] == GlyphRect(1, 1, 4, 3, 0, 5)
    assert rects[1] == GlyphRect(6, 1, 4, 5, 0, 5)
    # a third 4-wide glyph would end at 15 >= 12: new shelf below the tallest (5) plus the margin
    assert rects[2] == GlyphRect(1, 7, 4, 2, 0, 5)
    assert pixel(atlas, 12, 1, 1) == (10, 0, 0, 255)
    assert pixel(atlas, 12, 4, 3) == (10, 0, 0, 255)
    assert pixel(atlas, 12, 6, 5) == (20, 0, 0, 255)
    assert pixel(atlas, 12, 1, 7) == (30, 0, 0, 255)
    assert pixel(atlas, 12, 0, 0) == (0, 0, 0, 0)
    assert pixel(atlas, 12, 5, 1) == (0, 0, 0, 0)  # the margin column stays empty


def test_blank_glyphs_take_no_room_and_keep_their_metrics():
    blank = Glyph(32, 0, 0, 0, 6)
    atlas, (rects,) = pack_glyphs([[blank, solid(65, 3, 3, 1)]], 16, 16)
    assert rects[0] == GlyphRect(0, 0, 0, 0, 0, 6)
    assert rects[1].x == 1 and rects[1].y == 1


def test_sets_share_one_cursor():
    first = [solid(65, 3, 3, 1)]
    second = [solid(65, 3, 3, 2)]
    _, (a, b) = pack_glyphs([first, second], 32, 16)
    assert a[0].x == 1
    assert b[0].x == 5 and b[0].y == 1


def test_overflow_raises():
    with pytest.raises(ValueError):
        pack_glyphs([[solid(65, 4, 14, 1)]], 16, 16)
    with pytest.raises(ValueError):
        pack_glyphs([[solid(i, 4, 6, 1) for i in range(40)]], 16, 16)


def test_a_glyph_with_the_wrong_byte_count_is_rejected():
    with pytest.raises(ValueError):
        Glyph(65, 2, 2, 0, 3, bytes(15))


